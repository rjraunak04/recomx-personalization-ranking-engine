"""Recommendation-specific exploratory analysis for RecomX."""

from __future__ import annotations

from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd


@dataclass(frozen=True)
class RecommendationEDASummary:
    """Core recommendation-system EDA statistics."""

    interactions: int
    unique_users: int
    unique_items: int
    catalogue_items: int
    possible_user_item_pairs: int
    observed_user_item_pairs: int
    interaction_density: float
    sparsity: float
    mean_rating: float
    median_rating: float
    minimum_rating: float
    maximum_rating: float
    interactions_per_user_mean: float
    interactions_per_user_median: float
    interactions_per_user_p95: float
    interactions_per_item_mean: float
    interactions_per_item_median: float
    interactions_per_item_p95: float
    top_1pct_item_interaction_share: float
    top_10pct_item_interaction_share: float
    catalogue_rating_coverage: float
    start_timestamp: str
    end_timestamp: str

    def to_dict(self) -> dict[str, Any]:
        """Return JSON-serializable representation."""

        return asdict(self)


def calculate_sparsity(
    ratings: pd.DataFrame,
) -> tuple[int, int, float, float]:
    """Calculate observed user-item density and matrix sparsity."""

    unique_users = int(ratings["userId"].nunique())
    unique_items = int(ratings["movieId"].nunique())

    possible_pairs = unique_users * unique_items

    observed_pairs = int(ratings[["userId", "movieId"]].drop_duplicates().shape[0])

    density = observed_pairs / possible_pairs if possible_pairs else 0.0

    sparsity = 1.0 - density

    return (
        possible_pairs,
        observed_pairs,
        density,
        sparsity,
    )


def user_activity(
    ratings: pd.DataFrame,
) -> pd.Series:
    """Return interaction count for each user."""

    return (
        ratings.groupby(
            "userId",
            sort=False,
        )
        .size()
        .rename("interaction_count")
    )


def item_popularity(
    ratings: pd.DataFrame,
) -> pd.Series:
    """Return interaction count for each rated item."""

    return (
        ratings.groupby(
            "movieId",
            sort=False,
        )
        .size()
        .rename("interaction_count")
    )


def popularity_share(
    popularity: pd.Series,
    fraction: float,
) -> float:
    """Return interaction share generated by top item fraction."""

    if popularity.empty:
        return 0.0

    if not 0.0 < fraction <= 1.0:
        raise ValueError("fraction must be within (0, 1].")

    ordered = popularity.sort_values(ascending=False)

    top_n = max(
        1,
        int(np.ceil(len(ordered) * fraction)),
    )

    total = float(ordered.sum())

    if total == 0.0:
        return 0.0

    return float(ordered.iloc[:top_n].sum() / total)


def rating_distribution(
    ratings: pd.DataFrame,
) -> pd.DataFrame:
    """Build rating-frequency distribution."""

    counts = (
        ratings["rating"]
        .value_counts()
        .sort_index()
        .rename_axis("rating")
        .reset_index(name="interaction_count")
    )

    counts["share"] = counts["interaction_count"] / counts["interaction_count"].sum()

    return counts


def monthly_interactions(
    ratings: pd.DataFrame,
) -> pd.DataFrame:
    """Aggregate interactions by calendar month."""

    timestamps = ratings["timestamp"]

    if timestamps.dt.tz is not None:
        timestamps = timestamps.dt.tz_localize(None)

    months = timestamps.dt.to_period("M")

    counts = (
        months.value_counts()
        .sort_index()
        .rename_axis("month")
        .reset_index(name="interaction_count")
    )

    counts["month"] = counts["month"].astype(str)

    return counts


def build_summary(
    ratings: pd.DataFrame,
    movies: pd.DataFrame,
) -> RecommendationEDASummary:
    """Calculate recommendation-specific EDA summary."""

    users = user_activity(ratings)
    items = item_popularity(ratings)

    (
        possible_pairs,
        observed_pairs,
        density,
        sparsity,
    ) = calculate_sparsity(ratings)

    catalogue_items = int(movies["movieId"].nunique())

    rated_items = int(ratings["movieId"].nunique())

    catalogue_coverage = rated_items / catalogue_items if catalogue_items else 0.0

    return RecommendationEDASummary(
        interactions=int(len(ratings)),
        unique_users=int(ratings["userId"].nunique()),
        unique_items=rated_items,
        catalogue_items=catalogue_items,
        possible_user_item_pairs=possible_pairs,
        observed_user_item_pairs=observed_pairs,
        interaction_density=float(density),
        sparsity=float(sparsity),
        mean_rating=float(ratings["rating"].mean()),
        median_rating=float(ratings["rating"].median()),
        minimum_rating=float(ratings["rating"].min()),
        maximum_rating=float(ratings["rating"].max()),
        interactions_per_user_mean=float(users.mean()),
        interactions_per_user_median=float(users.median()),
        interactions_per_user_p95=float(users.quantile(0.95)),
        interactions_per_item_mean=float(items.mean()),
        interactions_per_item_median=float(items.median()),
        interactions_per_item_p95=float(items.quantile(0.95)),
        top_1pct_item_interaction_share=(
            popularity_share(
                items,
                0.01,
            )
        ),
        top_10pct_item_interaction_share=(
            popularity_share(
                items,
                0.10,
            )
        ),
        catalogue_rating_coverage=float(catalogue_coverage),
        start_timestamp=str(ratings["timestamp"].min()),
        end_timestamp=str(ratings["timestamp"].max()),
    )


def load_eda_tables(
    interim_dir: str | Path = "data/interim",
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Load only tables required by CP-05."""

    root = Path(interim_dir)

    ratings_path = root / "ratings.parquet"
    movies_path = root / "movies.parquet"

    if not ratings_path.is_file():
        raise FileNotFoundError(f"Missing ratings dataset: {ratings_path}")

    if not movies_path.is_file():
        raise FileNotFoundError(f"Missing movies dataset: {movies_path}")

    ratings = pd.read_parquet(
        ratings_path,
        columns=[
            "userId",
            "movieId",
            "rating",
            "timestamp",
        ],
    )

    movies = pd.read_parquet(
        movies_path,
        columns=[
            "movieId",
            "title",
            "genres",
        ],
    )

    return ratings, movies
